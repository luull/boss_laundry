-- ke sintaks PostgreSQL yang kompatibel dengan Supabase.
-- File asli `bozz_laundry.sql` TIDAK diubah.
--
-- CARA MENJALANKAN DI SUPABASE
-- 1. Buka dashboard Supabase project Anda.
-- 2. Masuk ke menu "SQL Editor" -> "New query".
-- 3. Salin seluruh isi file ini ke editor.
-- 4. Klik "Run" (atau Cmd/Ctrl + Enter).
-- 5. Pastikan muncul "Success. No rows returned".
-- 6. Verifikasi tabel di menu "Table Editor" (schema: public).
--
-- CATATAN PENTING
-- - Script ini membuat ulang tabel di schema `public`. Blok DROP di bawah
--   akan MENGHAPUS tabel lama BESERTA DATANYA bila sudah ada.
--   Jalankan hanya pada database baru / database setup awal, BUKAN pada
--   database produksi yang sudah berisi data penting.
-- - Tidak ada password / kredensial yang disimpan di dalam file ini.
-- - Perubahan utama vs MySQL:
--     * AUTO_INCREMENT          -> GENERATED BY DEFAULT AS IDENTITY
--     * int(11)                 -> integer
--     * double                  -> double precision
--     * decimal(10,2)           -> numeric(10,2)
--     * enum(...)               -> varchar + CHECK constraint
--     * text / varchar / date   -> tetap (kompatibel)
--   Nama tabel, nama kolom, relasi, PK, FK, index, dan data awal
--   dipertahankan apa adanya.
-- =====================================================================

